#!/usr/bin/env python3
"""Generate src/font8x16.h (ASCII 32..126, 8x16 bitmap) from the Terminus console font (OFL). Usage: gen_font.py [font.psfu.gz] > src/font8x16.h"""
import gzip
import struct
import sys

path = sys.argv[1] if len(sys.argv) > 1 else "/usr/lib/kbd/consolefonts/Lat2-Terminus16.psfu.gz"
data = gzip.open(path).read()
magic, ver, hdr, flags, length, charsize, height, width = struct.unpack("<IIIIIIII", data[:32])
assert magic == 0x864AB572 and width == 8 and height == 16, "expected a PSF2 8x16 font"
glyphs = [data[hdr + i * charsize: hdr + (i + 1) * charsize] for i in range(length)]
print("// Generated by tools/gen_font.py from %s (Terminus, SIL OFL 1.1). ASCII 32..126, 8x16, MSB = leftmost pixel." % path.split("/")[-1])
print("#pragma once\n#include <stdint.h>\n\nstatic const uint8_t FONT8X16[95][16] = {")
for c in range(32, 127):
    print("    {" + ",".join("0x%02X" % b for b in glyphs[c]) + "},  // '%s'" % (chr(c) if chr(c) != "\\" else "\\\\"))
print("};")
